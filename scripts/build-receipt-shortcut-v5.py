def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(plistlib.dumps(build(), fmt=plistlib.FMT_XML, sort_keys=False))
    print(OUT)


if __name__ == "__main__":
    main()
